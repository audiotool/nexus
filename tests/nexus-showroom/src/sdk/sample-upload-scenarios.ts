// -- Remove helpers --------------------------------------------------------

/**
 * Remove the audio track (and the region that points at it) that was
 * created by a scenario run. Used for the scenarios that create a new
 * track — A-H and I.
 */
export async function removeScenarioTrack(
  doc: SyncedDocument,
  track: NexusEntity<"audioTrack">,
): Promise<void> {
  await doc.modify((t) => t.removeWithDependencies(track))
}

/**
 * Remove just the region (and its automation events + collection) created
 * by a scenario run, leaving the host track in place. Used for scenario J,
 * where the sample was inserted onto a user-picked existing track.
 *
 * The associated `sample` entity is also removed; it is orphaned once the
 * region is gone.
 */
export async function removeScenarioRegion(
  doc: SyncedDocument,
  region: NexusEntity<"audioRegion">,
): Promise<void> {
  const sampleId = region.fields.sample.value.entityId
  const collectionId = region.fields.playbackAutomationCollection.value.entityId
  await doc.modify((t) => {
    // Removing the automation collection cascades to its events AND to the
    // audio region (both point to the collection), so the track is left
    // intact while the region is unwound.
    t.removeWithDependencies(collectionId)
    // Sample is now orphan — plain remove works.
    t.remove(sampleId)
  })
}

// -- Scenarios catalog -----------------------------------------------------

export type ScenarioId = "A" | "B" | "C" | "D" | "F" | "G" | "H" | "I" | "J"

type ScenarioCommon = {
  id: ScenarioId
  title: string
  description: string
  /** Which preset this scenario uses. Maps to a key of
   *  `PRESET_SAMPLE_IDS` and a filename under `public/samples/<id>.mp3`. */
  presetId: PresetSampleId
  /** The full insert call rendered as text, including the
   *  `client.samples.get(...)` lookup. */
  codeSnippet: string
}

/**
 * Scenario shape:
 *
 * - `kind: "standalone"` — no user input needed. `run` creates everything
 *   from scratch.
 * - `kind: "attach-device"` — the user picks an existing
 *   `audioDevice` and `run` adds a new track + region on it.
 * - `kind: "attach-track"` — the user picks an existing `audioTrack` and
 *   `run` stacks a new region onto it (no new track).
 *
 * `kind` is what the UI switches on to decide whether to render a target
 * picker.
 */
export type Scenario =
  | (ScenarioCommon & {
      kind: "standalone"
      run: (
        client: AuthenticatedClient,
        doc: SyncedDocument,
        displayName?: string,
      ) => Promise<ScenarioInsertResult>
    })
  | (ScenarioCommon & {
      kind: "attach-device"
      run: (
        client: AuthenticatedClient,
        doc: SyncedDocument,
        device: NexusEntity<"audioDevice">,
        displayName?: string,
      ) => Promise<ScenarioInsertResult>
    })
  | (ScenarioCommon & {
      kind: "attach-track"
      run: (
        client: AuthenticatedClient,
        doc: SyncedDocument,
        track: NexusEntity<"audioTrack">,
        displayName?: string,
      ) => Promise<ScenarioInsertResult>
    })

/** Helper to format the code snippet for each scenario uniformly. */
const codeForInsert = (presetId: PresetSampleId, body: string): string => {
  const id = PRESET_SAMPLE_IDS[presetId]
  return `const meta = await client.samples.get(
  "${id}",
)
if (meta instanceof Error) throw meta

await doc.modify((t) => ${body})`
}

/** Variant of {@link codeForInsert} that also shows where the user-picked
 *  attach target comes from. */
const codeForAttach = (
  presetId: PresetSampleId,
  pickerType: "audioDevice" | "audioTrack",
  pickerName: string,
  body: string,
): string => {
  const id = PRESET_SAMPLE_IDS[presetId]
  return `const meta = await client.samples.get(
  "${id}",
)
if (meta instanceof Error) throw meta

// Pick an existing entity from the document — here, the one
// selected in the dropdown to the right.
const ${pickerName}: NexusEntity<"${pickerType}"> = ...

await doc.modify((t) => ${body})`
}

