/** H. 125 bpm 4-bar sample; loop bars 2-4 of the sample, placed at region
 *     bars 3-6. The `loop.startTicks` also shifts where the sample begins
 *     playing, so the very first instant of the region is bar 2 of the
 *     sample. */
